function Block({ block }) {
  switch (block.type) {
    case "p":
      return <p>{block.text}</p>;
    case "ul":
      return (
        <ul>
          {block.items.map((item) => (
            <li key={item}>{item}</li>
          ))}
        </ul>
      );
    case "note":
      return (
        <aside className="pp-note" role="note">
          <strong>{block.title}</strong>
          <p>{block.text}</p>
        </aside>
      );
    case "contact":
      return (
        <p>
          <a className="pp-mail" href={`mailto:${CONTACT_EMAIL}`}>
            {CONTACT_EMAIL}
          </a>
        </p>
      );
    default:
      return null;
  }
}

export default function Privacy() {
  const [active, setActive] = useState(SECTIONS[0].id);

  useEffect(() => {
    if (!("IntersectionObserver" in window)) return;
    const observer = new IntersectionObserver(
      (entries) => {
        const visible = entries
          .filter((e) => e.isIntersecting)
          .sort((a, b) => a.boundingClientRect.top - b.boundingClientRect.top);
        if (visible.length) setActive(visible[0].target.id);
      },
      { rootMargin: "-15% 0px -70% 0px" }
    );
    SECTIONS.forEach(({ id }) => {
      const el = document.getElementById(id);
      if (el) observer.observe(el);
    });
    return () => observer.disconnect();
  }, []);

  return (
    <div className="pp">
      <header className="pp-header">
        <p className="pp-brand">{APP_NAME}</p>
        <h1>Сиёсати махфият</h1>
        <p className="pp-date">Аз санаи {EFFECTIVE_DATE} эътибор дорад</p>
      </header>

      <section className="pp-glance" aria-label="Дар як нигоҳ">
        <h2>Дар як нигоҳ</h2>
        <div className="pp-glance-grid">
          {GLANCE.map((g) => (
            <div key={g.title} className="pp-glance-item">
              <h3>{g.title}</h3>
              <p>{g.text}</p>
            </div>
          ))}
        </div>
      </section>

      <div className="pp-layout">
        <nav className="pp-toc" aria-label="Мундариҷа">
          <p className="pp-toc-title">Мундариҷа</p>
          <ol>
            {SECTIONS.map((s) => (
              <li key={s.id}>
                <a
                  href={`#${s.id}`}
                  className={active === s.id ? "is-active" : undefined}
                  aria-current={active === s.id ? "true" : undefined}
                >
                  {s.title}
                </a>
              </li>
            ))}
          </ol>
        </nav>

        <main className="pp-content">
          {SECTIONS.map((s, i) => (
            <section key={s.id} id={s.id} className="pp-section">
              <h2>
                <span className="pp-num">{i + 1}.</span> {s.title}
              </h2>
              {s.blocks.map((b, j) => (
                <Block key={j} block={b} />
              ))}
            </section>
          ))}
        </main>
      </div>

      <footer className="pp-footer">
        © {new Date().getFullYear()} {APP_NAME}
      </footer>
    </div>
  );
}